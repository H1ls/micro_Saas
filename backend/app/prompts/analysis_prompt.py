from __future__ import annotations

from app.domain.models import NormalizedDataset


ANALYSIS_SYSTEM_PROMPT = """
Анализируй только контекст датасета, переданный пользователем.
Верни только валидный JSON следующей структуры:
{
  "headline": "краткий главный инсайт",
  "insight_summary": "2-3 коротких предложения, основанных только на строках датасета",
  "narrative": "объяснение в 2-4 предложениях, основанное только на датасете",
  "key_observations": ["наблюдение, подтвержденное данными"],
  "charts": [
    {
      "id": "chart_1",
      "title": "название графика",
      "type": "bar",
      "x_key": "существующее имя столбца",
      "y_key": "существующее имя числового столбца",
      "reason": "почему этот график полезен",
      "filter": null
    }
  ]
}

Правила:
- Не используй внешние факты.
- Не придумывай столбцы, категории, значения, валюты, даты или события.
- Если данных недостаточно для утверждения, не включай его в ответ.
- Для MVP используй только типы графиков "bar", "line" и "pie".
- Ты выбираешь type, x_key и y_key, но не возвращаешь точки графика или числовые ряды.
- insight_summary должен быть 2-3 коротких предложения, не список и не техническое описание.
- insight_summary должен звучать как бизнес-наблюдение, например: "Выгрузка из Jira показывает, что 40% задач застряли на этапе ревью. Главное бутылочное горлышко - вторник."
- Если датасет получен из извлеченных фактов raw text, используй x_key "label", y_key "metric_value" и при необходимости добавляй filter по group и metric_key.
- Для обычных CSV/Excel-таблиц используй filter только тогда, когда каждый ключ фильтра является существующим столбцом датасета.
- Не добавляй фильтры group или metric_key, предназначенные только для raw text, если таких столбцов нет в контексте датасета.
- Пиши headline, insight_summary, narrative, key_observations, названия графиков и причины их выбора на русском языке.
- Название графика должно точно описывать отображаемую метрику и группировку, например: "Выручка по регионам".
- Если исходные данные используют русские подписи или русские названия столбцов, весь пользовательский текст должен быть полностью на русском языке.
- Не показывай технические ключи в пользовательских названиях графиков, если по датасету можно определить понятную русскую подпись.
""".strip()


def build_analysis_prompt(dataset: NormalizedDataset) -> str:
    """Строит user prompt из compact context, не передавая LLM весь исходный файл."""

    return (
        "Создай краткий аналитический текст для дашборда на основе этого контекста датасета.\n\n"
        f"{dataset.compact_context}\n\n"
        "Ограничения:\n"
        "- Используй только столбцы, присутствующие в контексте датасета.\n"
        "- headline должен быть короче 140 символов.\n"
        "- insight_summary должен содержать 2-3 коротких предложения и быть короче 360 символов.\n"
        "- insight_summary должен включать конкретные значения из датасета, если они доступны.\n"
        "- narrative должен быть короче 900 символов.\n"
        "- Верни от 1 до 3 key_observations.\n"
        "- Рекомендуй 2-3 графика, если доступные столбцы позволяют их построить.\n"
        "- Для графиков выбирай только type, x_key, y_key, title, reason и необязательный filter; данные для графика рассчитает backend.\n"
        "- Название графика должно точно соответствовать его содержимому: метрика из y_key по x_key или тренд метрики по x_key.\n"
        "- Если строки содержат group/label/metric_key/metric_value, используй filter, чтобы для каждого графика выделить одну группу и один metric_key.\n"
        "- Для CSV/Excel-датасетов устанавливай filter в null, если фильтр не использует реальные существующие столбцы из контекста.\n"
        "- Весь пользовательский текст пиши на русском языке; не смешивай английские технические ключи с названиями графиков, если доступны понятные русские подписи."
    )
